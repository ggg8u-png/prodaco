/** 이 지역의 표기 변형 전체(대표 표기가 항상 첫 번째). 없으면 대표 표기 하나만. */
export function regionVariants(region: string | undefined): string[] {
  if (!region) return [];
  return REGION_VARIANTS[region] ?? [region];
}

/**
 * 이 페이지에서 쓸 '보조 표기' — 대표 표기와 다른 것 하나를 결정적으로 고른다.
 * 변형이 없으면 null 이고, 호출부는 그때 대표 표기만 쓴다.
 */
export function altRegionLabel(region: string | undefined, slug: string, salt = 0): string | null {
  const vs = regionVariants(region).slice(1);
  if (!vs.length) return null;
  return pickBy(seedOf(slug), salt + 11, vs);
}

