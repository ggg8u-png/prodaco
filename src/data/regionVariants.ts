// ─── ③ 동(洞) 단위 확장 구조 ───────────────────────────────────────────────────
// 아직 동 단위 페이지를 대량 생성하지는 않는다(페이지 수를 무작정 늘리지 않는다).
// 다만 나중에 켤 때 데이터 구조를 새로 만들지 않아도 되도록 여기에 자리를 만들어 둔다.
//
// 운영자가 이 표에 동을 채우면:
//   · 지역 허브(/services/<시·구>)에서 "세부 지역" 목록으로 노출되고
//   · scripts/promote-keywords.mjs 로 동 단위 조합을 키워드 세트에 추가할 수 있다
// 채우지 않으면 어디에도 나타나지 않는다(빈 값이 기본 동작).
export const DONG_BY_REGION: Record<string, string[]> = {
  // 예시 형식 — 실제 운영 지역을 확인한 뒤 채운다.
  //   수원: ["영통동", "망포동", "광교동", "인계동"],
};

export function dongsOf(region: string | undefined): string[] {
  if (!region) return [];
  return DONG_BY_REGION[region] ?? [];
}

/** 동 단위 확장이 켜져 있는가(하나라도 등록된 지역이 있는가). */
export function hasDongExpansion(): boolean {
  return Object.values(DONG_BY_REGION).some((v) => v.length > 0);
}
