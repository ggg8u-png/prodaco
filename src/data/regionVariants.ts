// 지역·품목 표기 변형(variant) 사전 + 동 단위 확장 구조.
//
// 목적: 검색 쿼리는 "수원 마루철거"·"수원시 마루 철거"·"마루바닥 철거"처럼 표기가 갈리는데,
//   표기마다 URL 을 따로 만들면 같은 내용의 페이지가 몇 배로 불어난다(= 중복 콘텐츠).
//   그래서 URL(canonical)은 하나로 두고, title·description·H1·본문·FAQ 안에서만
//   변형 표기를 자연스럽게 쓴다. 같은 단어를 억지로 반복(keyword stuffing)하지 않는다.
//
// 선택은 전부 결정적(deterministic)이다 — 슬러그를 시드로 고르므로 같은 페이지는
// 언제 빌드해도 같은 표기가 나온다(빌드마다 문구가 흔들리면 그것 자체가 품질 신호를 해친다).

// ─── 시드 유틸(content.ts 와 동일 규칙) ───────────────────────────────────────
function seedOf(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
function pickBy<T>(seed: number, salt: number, arr: T[]): T {
  return arr[(seed + salt * 2654435761) % arr.length];
}

