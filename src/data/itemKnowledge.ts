/** 품목의 지식 프로파일. 개별 오버라이드 → 품목군 기본값 순으로 채운다. */
export function itemKnowledgeFor(item: string | undefined): ItemKnowledge {
  const base = BY_FAMILY[familyOf(item || "")] ?? BY_FAMILY.generic;
  const over = item ? BY_ITEM[item] : undefined;
  return over ? { ...base, ...over } : base;
}

/** 이 품목에 개별 오버라이드가 몇 개나 붙어 있는지(품질 감사용). */
export function itemKnowledgeOverrideCount(item: string | undefined): number {
  const over = item ? BY_ITEM[item] : undefined;
  return over ? Object.keys(over).length : 0;
}

