//     사실처럼 단정하지 않는다("최근 수원에서 20건" 같은 문장은 금지).
//   · 숫자는 넣지 않는다. 실제 단가는 content/costs.json(운영자 관리값)에서만 온다.
//   · 품목별로 process/checklist/costFactors 가 서로 달라야 의미가 있다 — 같은 문장을
//     여러 품목에 복사하지 않는다(scripts/seo-tests.ts 가 중복을 검사한다).
